"""The figures as an Excel workbook, ready for a model or a comparison.

Numbers are stored as numbers (with number formats), changes and free cash flow as formulas of the cells
they come from, and every row says the page where the figure is printed. Sheets: Summary, Statements,
Ratios, Checks, Figures (everything read, with its period) and, for market sheets, Prices and Returns.
"""
from __future__ import annotations

import io
from datetime import date

import xlsxwriter
from xlsxwriter.utility import xl_rowcol_to_cell

from . import financials as F
from .i18n import t, using
from .pdfreport import HIGHLIGHTS

RATIOS = (("gross_margin", ("Margine lordo", "Gross margin"), "pct"), ("operating_margin", ("Margine operativo", "Operating margin"), "pct"),
          ("net_margin", ("Margine netto", "Net margin"), "pct"), ("fcf_margin", ("Margine free cash flow", "Free cash flow margin"), "pct"),
          ("rnd_ratio", ("R&S su ricavi", "R&D to revenue"), "pct"), ("tax_rate", ("Aliquota fiscale effettiva", "Effective tax rate"), "pct"),
          ("interest_coverage", ("Copertura interessi", "Interest coverage"), "x"), ("current_ratio", ("Current ratio", "Current ratio"), "x"),
          ("debt_to_assets", ("Debito / attivo", "Debt to assets"), "pct"), ("equity_multiplier", ("Attivo / patrimonio netto", "Assets to equity"), "x"),
          ("return_pct_fcf", ("FCF restituito agli azionisti", "FCF returned to shareholders"), "pct"),
          ("sbc_pct_fcf", ("Compensi in azioni / FCF", "Stock comp. to FCF"), "pct"))


def _scale(m: dict) -> tuple[float, str]:
    top = max((abs(v) for x in m.values() if x.get("kind") in ("flow", "stock") for v in (x.get("cur"), x.get("prev")) if v is not None), default=0)
    if top >= 1e8:
        return 1e6, t("milioni", "millions")
    if top >= 1e5:
        return 1e3, t("migliaia", "thousands")
    return 1.0, ""


def build(a: dict) -> bytes:
    with using(a.get("lang") or "en"):
        return _build(a)


def _build(a: dict) -> bytes:
    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {"in_memory": True, "strings_to_numbers": False, "strings_to_urls": False})
    wb.set_properties({"title": f"{a.get('title', '')} — Spider Analyst", "author": "Spider Analyst"})
    labels = {str(k): v for k, v in (a.get("page_labels") or {}).items()}

    def pages(pp) -> str:
        pp = list(dict.fromkeys(p for p in pp or [] if p))
        return ", ".join(str(labels.get(str(p)) or p) for p in pp)

    f_title = wb.add_format({"bold": True, "font_size": 16, "font_name": "Calibri"})
    f_sub = wb.add_format({"font_color": "#6C6A7C"})
    f_head = wb.add_format({"bold": True, "bg_color": "#F4F3F8", "bottom": 1, "border_color": "#D6D4E0", "text_wrap": True, "valign": "vcenter"})
    f_group = wb.add_format({"bold": True, "top": 1, "border_color": "#1D1C26"})
    f_text = wb.add_format({"text_wrap": True, "valign": "top"})
    f_num = wb.add_format({"num_format": "#,##0.0;[Red]-#,##0.0"})
    f_int = wb.add_format({"num_format": "#,##0;[Red]-#,##0"})
    f_ps = wb.add_format({"num_format": "#,##0.00;[Red]-#,##0.00"})
    f_pct = wb.add_format({"num_format": "0.0%;[Red]-0.0%"})
    f_x = wb.add_format({"num_format": '0.0"x"'})
    f_ok = wb.add_format({"bold": True, "font_color": "#0F8A5F"})
    f_no = wb.add_format({"bold": True, "font_color": "#C8323C"})
    f_page = wb.add_format({"font_color": "#C2185B", "bold": True, "align": "right"})
    f_note = wb.add_format({"italic": True, "font_color": "#6C6A7C", "text_wrap": True})

    fin = a.get("fin") or {}
    m, d, cur = fin.get("metrics") or {}, fin.get("derived") or {}, fin.get("currency") or a.get("currency") or ""
    rd = a.get("reading") or {}

    # ---------------------------------------------------------------- Summary
    ws = wb.add_worksheet(t("Sintesi", "Summary"))
    ws.set_column(0, 0, 34)
    ws.set_column(1, 1, 16)
    ws.set_column(2, 5, 14)
    ws.set_column(6, 6, 12)
    ws.write(0, 0, a.get("title") or "", f_title)
    ws.write(1, 0, a.get("subtitle") or "", f_sub)
    ws.write(2, 0, t("Fonte: ", "Source: ") + (a.get("source") or ""), f_sub)
    ws.write(3, 0, t("Generato da Spider Analyst il ", "Generated by Spider Analyst on ") + date.today().isoformat() +
             t(". Non è una consulenza finanziaria.", ". Not financial advice."), f_sub)
    r = 5
    lang = a.get("lang") or "en"
    if a.get("card"):
        ws.write_row(r, 0, [t("Cifra chiave", "Headline figure"), t("Valore", "Value"), t("Esatto", "Exact"), t("Variazione", "Change"),
                            t("Confronto", "Compared with"), t("Nota", "Note"), t("Pagina", "Page")], f_head)
        for tile in a["card"]:
            r += 1
            label = tile.get("en") if lang == "en" and tile.get("en") else tile.get("it")
            ws.write(r, 0, label or "")
            ws.write(r, 1, tile.get("display") or "—")
            ws.write(r, 2, tile.get("exact") or "")
            ws.write(r, 3, tile.get("yoy_display") or (t("era ", "was ") + tile["prev_display"] if tile.get("prev_display") else ""))
            ws.write(r, 4, tile.get("vs") or "")
            ws.write(r, 5, tile.get("note") or "")
            ws.write(r, 6, pages(tile.get("pages")), f_page)
        r += 2
    if rd.get("summary"):
        ws.write(r, 0, t("In breve", "In short"), f_group)
        r += 1
        ws.merge_range(r, 0, r, 6, rd["summary"], f_text)
        ws.set_row(r, 15 * max(2, len(rd["summary"]) // 110 + 1))
        r += 2
    if a.get("findings"):
        ws.write(r, 0, t("Osservazioni chiave", "Key findings"), f_group)
        for fd in a["findings"]:
            r += 1
            ws.merge_range(r, 0, r, 5, fd.get("text") or "", f_text)
            ws.write(r, 6, pages(fd.get("pages")), f_page)
            ws.set_row(r, 15 * max(1, len(fd.get("text") or "") // 100 + 1))
        r += 2
    for sec in rd.get("sections") or []:
        ws.write(r, 0, sec.get("title") or "", f_group)
        for p in sec.get("points") or []:
            r += 1
            ws.merge_range(r, 0, r, 5, p.get("text") or "", f_text)
            ws.write(r, 6, pages(p.get("pages")), f_page)
            ws.set_row(r, 15 * max(1, len(p.get("text") or "") // 100 + 1))
        r += 2

    # ---------------------------------------------------------------- Statements
    if len(m) >= 2:
        ws = wb.add_worksheet(t("Prospetti", "Statements"))
        div, scale = _scale(m)
        per = fin.get("periods") or {}
        flow = per.get("flow") or [str(y) for y in fin.get("years") or ["", ""]]
        stock = per.get("stock") or flow
        ws.set_column(0, 0, 44)
        ws.set_column(1, 2, 16)
        ws.set_column(3, 3, 12)
        ws.set_column(4, 4, 16)
        ws.set_column(5, 5, 10)
        unit = " ".join(x for x in (cur, scale) if x)
        ws.write(0, 0, a.get("title") or "", f_title)
        ws.write(1, 0, t(f"Importi in {unit}; per azione in {cur or 'valuta'}; azioni in {scale or 'unità'}.",
                         f"Amounts in {unit}; per share in {cur or 'currency'}; shares in {scale or 'units'}.") if unit else "", f_sub)
        r = 3
        rows: dict[str, int] = {}
        vals: dict[int, list] = {}           # row -> [current, comparative] as written, for cached formula results
        for name, kind, keys in HIGHLIGHTS:
            labels_ = stock if kind == "stock" else flow
            present = [k for k in keys if k in m and m[k].get("cur") is not None] + (["fcf"] if "fcf" in keys and "cfo" in m and "capex" in m else [])
            if not present:
                continue
            ws.write_row(r, 0, [t(*name), labels_[0] if labels_ else "", labels_[1] if len(labels_) > 1 else "", t("Variazione", "Change"),
                                t("Unità", "Unit"), t("Pagina", "Page")], f_head)
            for k in [k for k in keys if k in present]:
                r += 1
                if k == "fcf":
                    rc, rk = rows.get("cfo"), rows.get("capex")
                    if rc is None or rk is None:
                        r -= 1
                        continue
                    ws.write(r, 0, t("Free cash flow (calcolato: cassa operativa − capex)", "Free cash flow (computed: operating cash flow − capex)"))
                    vals[r] = [None, None]
                    for col in (1, 2):
                        o, c = vals[rc][col - 1], vals[rk][col - 1]
                        vals[r][col - 1] = None if o is None or c is None else o - abs(c)
                        ws.write_formula(r, col, f"=IF(OR({xl_rowcol_to_cell(rc, col)}=\"\",{xl_rowcol_to_cell(rk, col)}=\"\"),\"\","
                                                 f"{xl_rowcol_to_cell(rc, col)}-ABS({xl_rowcol_to_cell(rk, col)}))", f_num,
                                         "" if vals[r][col - 1] is None else vals[r][col - 1])
                    ws.write(r, 4, unit)
                    ws.write(r, 5, pages([m["cfo"].get("page"), m["capex"].get("page")]), f_page)
                else:
                    x = m[k]
                    mk = F.METRICS.get(k, ("", "", "flow"))[2]
                    lbl = t("Perdita netta", "Net loss") if k == "net_income" and (x.get("cur") or 0) < 0 else F.label(k)
                    ws.write(r, 0, lbl)
                    vals[r] = [None, None]
                    for col, w in ((1, "cur"), (2, "prev")):
                        v = x.get(w)
                        if v is not None:
                            vals[r][col - 1] = v if mk == "ps" else v / div
                        if v is None:
                            ws.write_blank(r, col, None)
                        elif mk == "ps":
                            ws.write_number(r, col, v, f_ps)
                        else:
                            ws.write_number(r, col, v / div, f_num)
                    ws.write(r, 4, f"{cur}/{t('azione', 'share')}" if mk == "ps" else (scale or t("unità", "units")) if mk == "shares" else unit)
                    ws.write(r, 5, pages([x.get("page")]), f_page)
                rows[k] = r
                b, p = xl_rowcol_to_cell(r, 1), xl_rowcol_to_cell(r, 2)
                # the change only when both periods have the same sign: a loss against a profit has no meaningful %
                bv, pv = vals[r]
                chg = (bv - pv) / pv if bv is not None and pv and bv * pv > 0 and pv > 0 else ""
                ws.write_formula(r, 3, f'=IF(OR({p}="",{b}="",{p}=0),"",IF({p}*{b}>0,IF({p}>0,({b}-{p})/{p},""),""))', f_pct, chg)
            r += 2
        ws.freeze_panes(3, 1)

    # ---------------------------------------------------------------- Ratios
    if d.get("cur"):
        rr = [(k, lbl, kind) for k, lbl, kind in RATIOS if d["cur"].get(k) is not None]
        if rr:
            ws = wb.add_worksheet(t("Indicatori", "Ratios"))
            years = [str(y) for y in fin.get("years") or ["", ""]]
            ws.set_column(0, 0, 36)
            ws.set_column(1, 3, 14)
            ws.write_row(0, 0, [t("Indicatore", "Ratio"), years[0], years[1] if len(years) > 1 else "", t("Variazione", "Change")], f_head)
            for i, (k, lbl, kind) in enumerate(rr, start=1):
                fmt = f_pct if kind == "pct" else f_x
                ws.write(i, 0, t(*lbl))
                ws.write_number(i, 1, d["cur"][k], fmt)
                if d.get("prev", {}).get(k) is not None:
                    ws.write_number(i, 2, d["prev"][k], fmt)
                    ws.write_formula(i, 3, f"={xl_rowcol_to_cell(i, 1)}-{xl_rowcol_to_cell(i, 2)}", fmt, d["cur"][k] - d["prev"][k])
            ws.write(len(rr) + 2, 0, t("Calcolati dalle cifre del documento.", "Computed from the document's figures."), f_note)

    # ---------------------------------------------------------------- Checks
    checks = a.get("checks") or []
    if checks:
        ws = wb.add_worksheet(t("Controlli", "Checks"))
        ws.set_column(0, 0, 8)
        ws.set_column(1, 1, 70)
        ws.set_column(2, 2, 60)
        ws.set_column(3, 4, 12)
        ws.write_row(0, 0, [t("Esito", "Result"), t("Controllo", "Check"), t("Dettaglio", "Detail"), t("Scarto %", "Gap %"), t("Pagine", "Pages")], f_head)
        for i, c in enumerate(checks, start=1):
            ws.write(i, 0, "OK" if c.get("ok") else "NO", f_ok if c.get("ok") else f_no)
            ws.write(i, 1, c.get("name") or "")
            ws.write(i, 2, c.get("detail") or "")
            if c.get("diff_pct") is not None:
                ws.write_number(i, 3, c["diff_pct"] / 100, f_pct)
            ws.write(i, 4, pages(c.get("pages")), f_page)

    # ---------------------------------------------------------------- Figures read
    facts = a.get("facts") or {}
    facts = list(facts.values()) if isinstance(facts, dict) else list(facts)
    if facts:
        ws = wb.add_worksheet(t("Cifre lette", "Figures read"))
        ws.set_column(0, 0, 60)
        ws.set_column(1, 1, 18)
        ws.set_column(2, 2, 18)
        ws.set_column(3, 4, 10)
        ws.write_row(0, 0, [t("Voce", "Line"), t("Valore", "Value"), t("Periodo", "Period"), t("Pagina", "Page"), t("Cifra chiave", "Headline")], f_head)
        for i, f in enumerate(facts, start=1):
            ws.write(i, 0, f.get("label") or "")
            ws.write(i, 1, f.get("value_fmt") or f.get("display") or "")
            ws.write(i, 2, f.get("period") or "")
            ws.write(i, 3, pages([f.get("page")]), f_page)
            ws.write(i, 4, F.label(f["metric"]) if f.get("metric") in F.METRICS else "")
        ws.autofilter(0, 0, len(facts), 4)
        ws.freeze_panes(1, 0)

    # ---------------------------------------------------------------- Market sheet
    sr = a.get("series") or {}
    if sr.get("points"):
        ws = wb.add_worksheet(t("Prezzi", "Prices"))
        f_date = wb.add_format({"num_format": "yyyy-mm-dd"})
        ws.set_column(0, 1, 14)
        ws.write_row(0, 0, [t("Data", "Date"), t("Chiusura", "Close") + (f" ({sr.get('currency')})" if sr.get("currency") else "")], f_head)
        for i, (dt, v) in enumerate(sr["points"], start=1):
            try:
                ws.write_datetime(i, 0, date.fromisoformat(dt[:10]), f_date)
            except ValueError:
                ws.write(i, 0, dt)
            ws.write_number(i, 1, v, f_ps)
        ws.freeze_panes(1, 0)
        ws.write(0, 3, t("Storico campionato (fino a 600 punti); lo storico completo è nel CSV dei risultati di ricerca.",
                         "Sampled history (up to 600 points); the full history is the CSV from the search results."), f_note)
    if sr.get("annual"):
        ws = wb.add_worksheet(t("Rendimenti", "Returns"))
        ws.set_column(0, 2, 14)
        ws.write_row(0, 0, [t("Anno", "Year"), t("Rendimento", "Return"), t("Parziale", "Partial")], f_head)
        for i, (y, ret, partial) in enumerate(sr["annual"], start=1):
            ws.write_number(i, 0, int(y), f_int) if str(y).isdigit() else ws.write(i, 0, str(y))
            ws.write_number(i, 1, ret, f_pct)
            ws.write(i, 2, t("sì", "yes") if partial else "")
    wb.close()
    return buf.getvalue()
